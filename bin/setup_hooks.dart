import 'dart:io';

import 'package:args/args.dart';
import 'package:dart_test_tools/src/hooks/hook_installer.dart';
import 'package:dart_test_tools/src/tools/github.dart';

void main(List<String> args) => Github.runZoned(() async {
  final parser =
      ArgParser(
          usageLineLength: stdout.hasTerminal ? stdout.terminalColumns : null,
        )
        ..addFlag(
          'flutter-compat',
          defaultsTo: true,
          help:
              'Check the flutter compatibility in the pre-push hook. Disable '
              'it for dart packages that are deliberately not compatible with '
              'flutter.',
        )
        ..addFlag(
          'force',
          negatable: false,
          help:
              'Overwrite existing hooks that were not generated by this '
              'command.',
        )
        ..addFlag('help', abbr: 'h', negatable: false, help: 'Show this help.');

  try {
    final options = parser.parse(args);

    if (options['help'] as bool) {
      stdout.writeln(parser.usage);
      return;
    }

    final flutterCompat = options['flutter-compat'] as bool;
    final installer = HookInstaller(Directory.current);
    final warnings = await installer.warnings(flutterCompat: flutterCompat);
    for (final warning in warnings) {
      stderr.writeln('Warning: $warning');
    }

    final hooks = await installer.install(
      flutterCompat: flutterCompat,
      force: options['force'] as bool,
    );
    for (final hook in hooks) {
      stdout.writeln('Installed ${hook.path}');
    }
  } on FormatException catch (e) {
    stderr
      ..writeln('Error: ${e.message}\n')
      ..writeln('Usage:')
      ..writeln(parser.usage);
    exitCode = 1;
  } on ForeignHooksException catch (e) {
    stderr.writeln('Error: ${e.message}');
    exitCode = 1;
  }
});
